<?php

declare(strict_types=1);

namespace App\Ai;

use ContentBlocks\Ai\AiAction;
use ContentBlocks\Ai\AiProviderInterface;
use ContentBlocks\Ai\AltTextRequest;
use ContentBlocks\Ai\ContentRequest;
use ContentBlocks\Ai\TextRequest;
use Symfony\Component\HttpFoundation\RequestStack;

/**
 * An AI provider that calls no model: every answer is computed from the
 * request, the same way every time.
 *
 * ---- Why the sandbox ships one ----
 *
 * Same reason as PseudoTranslationProvider. What is worth testing end to end
 * is the round trip — a click in the builder, the provider seam, the paste
 * replay that keeps a model's mistakes out of the draft, the undo step — and
 * none of it depends on the quality of the writing. A real model would cost a
 * key in CI and make the suite as flaky as someone else's API.
 *
 * The output is deliberately recognisable (a ✦ in front of a rewrite, the
 * prompt quoted in the generated title) so nobody mistakes it for real copy.
 *
 * It is also the shape to copy: implementing AiProviderInterface is the whole
 * registration. `generateContent()` shows the one rule that matters — write
 * only block types the schema lists, in the shape it describes.
 *
 * The `cb_e2e_ai_off` cookie (debug only) lists actions this provider refuses,
 * so Playwright can pin "an unsupported action is not offered".
 */
final class DemoAiProvider implements AiProviderInterface
{
    public function __construct(
        private readonly RequestStack $requests,
        private readonly bool $debug = false,
    ) {
    }

    public function supports(string $action): bool
    {
        $off = $this->debug ? (string) $this->requests->getCurrentRequest()?->cookies->get('cb_e2e_ai_off', '') : '';

        return !\in_array($action, explode(',', $off), true);
    }

    public function rewriteText(TextRequest $request): string
    {
        $plain = trim(html_entity_decode(strip_tags($request->text), \ENT_QUOTES | \ENT_HTML5));

        $text = match ($request->action) {
            AiAction::SHORTEN => self::shorten($plain),
            AiAction::TONE => match ($request->tone) {
                'friendly' => 'Hi there! ' . $plain,
                'persuasive' => rtrim($plain, '.!') . '. Try it today.',
                'playful' => $plain . ' 🎉',
                default => $plain,
            },
            default => '✦ ' . $plain,
        };

        if ($request->maxLength !== null && mb_strlen($text) > $request->maxLength) {
            $text = rtrim(mb_substr($text, 0, max(1, $request->maxLength - 1))) . '…';
        }

        return $request->html ? '<p>' . htmlspecialchars($text, \ENT_QUOTES) . '</p>' : $text;
    }

    public function describeImage(AltTextRequest $request): string
    {
        $name = pathinfo((string) parse_url($request->src, \PHP_URL_PATH), \PATHINFO_FILENAME);
        // Uploads carry a hash suffix: `sneaker-6650f1c2`.
        $name = preg_replace('/[-_][0-9a-f]{6,}$/i', '', $name) ?? $name;
        $words = trim(preg_replace('/[-_]+/', ' ', $name) ?? '');

        // A bare number (a stock photo id) says nothing about the picture.
        return $words === '' || ctype_digit(str_replace(' ', '', $words)) ? 'An image' : ucfirst($words);
    }

    public function generateContent(ContentRequest $request): array
    {
        $types = array_column($request->schema->blocks, 'type');
        $layouts = array_column($request->schema->layouts, 'columns', 'name');
        $subject = mb_substr(trim(preg_replace('/\s+/', ' ', $request->prompt) ?? ''), 0, 80);

        $sections = [$this->hero($subject, $types, $layouts)];
        if ($request->action === AiAction::PAGE) {
            $sections[] = $this->features($types, $layouts);
            $sections[] = $this->faq($types);
            $sections[] = $this->closing($subject, $types);
        }

        return ['sections' => \array_slice(array_values(array_filter($sections)), 0, $request->maxSections)];
    }

    /**
     * @param list<string>               $types
     * @param array<string, list<string>> $layouts
     *
     * @return array<string, mixed>
     */
    private function hero(string $subject, array $types, array $layouts): array
    {
        $blocks = [
            self::block($types, 'title', ['text' => $subject, 'size' => 'h1', 'tag' => 'h1']),
            self::block($types, 'text', ['content' => 'Generated by the demo provider from your prompt. Replace it with your own words.']),
            self::block($types, 'button', ['text' => 'Get started', 'url' => '/contact', 'variant' => 'primary']),
        ];

        return self::section('full', $layouts, [array_values(array_filter($blocks))]);
    }

    /**
     * @param list<string>               $types
     * @param array<string, list<string>> $layouts
     *
     * @return array<string, mixed>|null
     */
    private function features(array $types, array $layouts): ?array
    {
        if (!\in_array('card', $types, true)) {
            return null;
        }
        $items = [];
        foreach (['Fast', 'Simple', 'Reliable'] as $word) {
            $items[] = ['title' => $word, 'content' => $word . ' — a benefit worth saying.', 'src' => '', 'url' => '', 'buttonText' => ''];
        }

        return self::section('full', $layouts, [[
            self::block($types, 'title', ['text' => 'Why choose it', 'size' => 'h2', 'tag' => 'h2']),
            self::block($types, 'card', ['layout' => 'grid', 'columns' => 3, 'items' => $items]),
        ]]);
    }

    /**
     * @param list<string> $types
     *
     * @return array<string, mixed>|null
     */
    private function faq(array $types): ?array
    {
        if (!\in_array('accordion', $types, true)) {
            return null;
        }

        return self::section('full', [], [[
            self::block($types, 'title', ['text' => 'Questions', 'size' => 'h2', 'tag' => 'h2']),
            self::block($types, 'accordion', ['items' => [
                ['title' => 'How does it work?', 'content' => 'Simply.'],
                ['title' => 'What does it cost?', 'content' => 'Less than you think.'],
            ]]),
        ]]);
    }

    /**
     * @param list<string> $types
     *
     * @return array<string, mixed>
     */
    private function closing(string $subject, array $types): array
    {
        return self::section('full', [], [[
            self::block($types, 'title', ['text' => 'Ready? ' . $subject, 'size' => 'h2', 'tag' => 'h2']),
            self::block($types, 'button', ['text' => 'Buy now', 'url' => '/buy', 'variant' => 'primary', 'size' => 'lg']),
        ]]);
    }

    /**
     * @param array<string, list<string>>       $layouts
     * @param list<list<array<string, mixed>|null>> $columns
     *
     * @return array<string, mixed>
     */
    private static function section(string $layout, array $layouts, array $columns): array
    {
        $out = [];
        foreach ($columns as $blocks) {
            $out[] = ['preset' => 'col-12', 'blocks' => array_values(array_filter($blocks))];
        }

        return ['format' => 'content-blocks/section-v1', 'layout' => $layout, 'columns' => $out];
    }

    /**
     * A block only when the schema lists its type: an unknown one would be
     * skipped on the way in anyway.
     *
     * @param list<string>         $types
     * @param array<string, mixed> $data
     *
     * @return array<string, mixed>|null
     */
    private static function block(array $types, string $type, array $data): ?array
    {
        return \in_array($type, $types, true) ? ['type' => $type, 'data' => $data] : null;
    }

    private static function shorten(string $text): string
    {
        if (preg_match('/^(.+?[.!?])(\s|$)/u', $text, $m) === 1 && $m[1] !== $text) {
            return $m[1];
        }
        $words = preg_split('/\s+/', $text) ?: [];

        return \count($words) > 6 ? implode(' ', \array_slice($words, 0, 6)) . '…' : $text;
    }
}
